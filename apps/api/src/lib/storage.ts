import { randomBytes } from 'node:crypto';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { PrismaClient } from '@prisma/client';
import type { AppConfig } from '../config';

/**
 * Object storage for document ciphertext. Drivers never see plaintext: the
 * documents module encrypts before `put` and decrypts after `get`.
 */
export interface ObjectStorage {
  readonly driver: string;
  put(key: string, data: Buffer): Promise<void>;
  get(key: string): Promise<Buffer>;
  delete(key: string): Promise<void>;
}

const KEY_PATTERN = /^[a-f0-9]{64}$/;

/** Random storage names: they reveal nothing about the owner or the file. */
export function newStorageKey(): string {
  return randomBytes(32).toString('hex');
}

function assertKey(key: string) {
  // Keys are generated by newStorageKey(); anything else could be a path traversal attempt.
  if (!KEY_PATTERN.test(key)) throw new Error('Invalid storage key');
}

class LocalDiskStorage implements ObjectStorage {
  readonly driver = 'local';
  constructor(private readonly root: string) {}

  private pathFor(key: string) {
    assertKey(key);
    return path.join(this.root, key.slice(0, 2), `${key}.bin`);
  }

  async put(key: string, data: Buffer) {
    const file = this.pathFor(key);
    await mkdir(path.dirname(file), { recursive: true, mode: 0o700 });
    await writeFile(file, data, { mode: 0o600 });
  }

  async get(key: string) {
    return readFile(this.pathFor(key));
  }

  async delete(key: string) {
    await rm(this.pathFor(key), { force: true });
  }
}

class DatabaseStorage implements ObjectStorage {
  readonly driver = 'database';
  constructor(private readonly prisma: PrismaClient) {}

  async put(key: string, data: Buffer) {
    assertKey(key);
    await this.prisma.storedObject.create({ data: { key, data: new Uint8Array(data) } });
  }

  async get(key: string) {
    assertKey(key);
    const row = await this.prisma.storedObject.findUnique({ where: { key } });
    if (!row) throw new Error('Stored object not found');
    return Buffer.from(row.data);
  }

  async delete(key: string) {
    assertKey(key);
    await this.prisma.storedObject.deleteMany({ where: { key } });
  }
}

export function createStorage(config: AppConfig, prisma: PrismaClient): ObjectStorage {
  if (config.env.STORAGE_DRIVER === 'database') return new DatabaseStorage(prisma);
  return new LocalDiskStorage(path.resolve(config.env.STORAGE_DIR));
}

/** Writes, reads back and deletes a probe object. Used by the admin health check. */
export async function checkStorage(storage: ObjectStorage): Promise<void> {
  const key = newStorageKey();
  const probe = randomBytes(16);
  await storage.put(key, probe);
  try {
    const back = await storage.get(key);
    if (!back.equals(probe)) throw new Error('Storage read-back mismatch');
  } finally {
    await storage.delete(key);
  }
}
